export type FrontePack = 'pop' | 'casa' | 'natura' | 'difficile';

export interface FronteCard {
  word: string;
  taboo: [string, string, string, string];
  pack: FrontePack;
}

const c = (pack: FrontePack, word: string, taboo: string): FronteCard => {
  const t = taboo.split(',').map((x) => x.trim());
  return { pack, word, taboo: [t[0], t[1], t[2], t[3]] };
};

